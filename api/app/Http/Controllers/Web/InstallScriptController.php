<?php

namespace App\Http\Controllers\Web;

use App\Http\Controllers\Controller;

/**
 * Serves one-line installers generated from the current environment, so changing the domain or
 * server address in .env changes what new users get, with no rebuild of the binaries.
 */
class InstallScriptController extends Controller
{
    private function base(): string
    {
        return rtrim((string) config('app.url'), '/');
    }

    private function server(): string
    {
        return config('tunnel.server_host').':'.config('tunnel.control_port');
    }

    private function shq(string $v): string
    {
        return "'".str_replace("'", "'\\''", $v)."'";
    }

    private function psq(string $v): string
    {
        return "'".str_replace("'", "''", $v)."'";
    }

    public function sh()
    {
        $base = $this->shq($this->base());
        $server = $this->shq($this->server());
        $tls = config('tunnel.tls') ? 'on' : 'off';
        $script = <<<SH
#!/bin/sh
# Publish CLI installer (Linux / macOS). Generated by your Publish server.
set -eu
BASE={$base}
SERVER={$server}

os=\$(uname -s | tr 'A-Z' 'a-z')
case "\$os" in linux|darwin) ;; *) echo "Unsupported OS: \$os (on Windows use: irm \$BASE/install.ps1 | iex)" >&2; exit 1 ;; esac
case "\$(uname -m)" in x86_64|amd64) arch=amd64 ;; aarch64|arm64) arch=arm64 ;; *) echo "Unsupported CPU: \$(uname -m)" >&2; exit 1 ;; esac
name="publish-\$os-\$arch"

tmp=\$(mktemp)
trap 'rm -f "\$tmp" "\$tmp.sums"' EXIT
echo "Downloading \$name from \$BASE ..."
curl -fsSL "\$BASE/downloads/\$name" -o "\$tmp"

if curl -fsSL "\$BASE/downloads/SHA256SUMS" -o "\$tmp.sums" 2>/dev/null; then
  want=\$(grep " \$name\\\$" "\$tmp.sums" | awk '{print \$1}')
  if command -v sha256sum >/dev/null 2>&1; then have=\$(sha256sum "\$tmp" | awk '{print \$1}'); else have=\$(shasum -a 256 "\$tmp" | awk '{print \$1}'); fi
  if [ -n "\$want" ] && [ "\$want" != "\$have" ]; then echo "Checksum mismatch, aborting." >&2; exit 1; fi
fi
chmod +x "\$tmp"

dest=/usr/local/bin
if [ -w "\$dest" ]; then
  install -m 755 "\$tmp" "\$dest/publish"
elif command -v sudo >/dev/null 2>&1; then
  echo "Installing to \$dest (sudo may ask for your password) ..."
  sudo install -m 755 "\$tmp" "\$dest/publish"
else
  dest="\$HOME/.local/bin"; mkdir -p "\$dest"
  install -m 755 "\$tmp" "\$dest/publish"
  case ":\$PATH:" in *":\$dest:"*) ;; *) echo "Add \$dest to your PATH to run 'publish'." ;; esac
fi

"\$dest/publish" config server "\$SERVER" >/dev/null
"\$dest/publish" config tls {$tls} >/dev/null
echo
echo "Installed: \$("\$dest/publish" version)"
echo "Next:"
echo "  1. Create a token at \$BASE/tokens"
echo "  2. Run:  publish login"
echo "  3. Run:  publish http 5003      (replace 5003 with your app's port)"
SH;

        return response($script, 200, ['Content-Type' => 'text/x-shellscript; charset=utf-8', 'Cache-Control' => 'no-store']);
    }

    public function ps1()
    {
        $base = $this->psq($this->base());
        $server = $this->psq($this->server());
        $tls = config('tunnel.tls') ? 'on' : 'off';
        $script = <<<PS
# Publish CLI installer (Windows PowerShell). Generated by your Publish server.
\$ErrorActionPreference = 'Stop'
\$base = {$base}
\$server = {$server}
if (-not [Environment]::Is64BitOperatingSystem) { throw 'Only 64-bit Windows is supported.' }
\$dir = Join-Path \$env:LOCALAPPDATA 'Publish'
New-Item -ItemType Directory -Force -Path \$dir | Out-Null
\$exe = Join-Path \$dir 'publish.exe'
\$tmp = Join-Path \$env:TEMP 'publish-download.exe'
Write-Host "Downloading from \$base ..."
Invoke-WebRequest -UseBasicParsing "\$base/downloads/publish-windows-amd64.exe" -OutFile \$tmp
try {
  \$sums = (Invoke-WebRequest -UseBasicParsing "\$base/downloads/SHA256SUMS").Content
  \$want = (\$sums -split "`n" | Where-Object { \$_ -match 'publish-windows-amd64.exe\$' } | ForEach-Object { (\$_ -split '\s+')[0] }) | Select-Object -First 1
  \$have = (Get-FileHash \$tmp -Algorithm SHA256).Hash.ToLower()
  if (\$want -and \$want -ne \$have) { Remove-Item \$tmp; throw 'Checksum mismatch, aborting.' }
} catch [System.Net.WebException] { }
Move-Item -Force \$tmp \$exe
\$userPath = [Environment]::GetEnvironmentVariable('Path', 'User')
if ((\$userPath -split ';') -notcontains \$dir) { [Environment]::SetEnvironmentVariable('Path', "\$userPath;\$dir", 'User'); \$env:Path += ";\$dir" }
& \$exe config server \$server | Out-Null
& \$exe config tls {$tls} | Out-Null
Write-Host ''
Write-Host ('Installed: ' + (& \$exe version))
Write-Host 'Next:'
Write-Host "  1. Create a token at \$base/tokens"
Write-Host '  2. Open a NEW terminal and run:  publish login'
Write-Host '  3. Run:  publish http 5003      (replace 5003 with your app port)'
PS;

        return response($script, 200, ['Content-Type' => 'text/plain; charset=utf-8', 'Cache-Control' => 'no-store']);
    }
}
